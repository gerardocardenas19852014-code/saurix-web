create schema if not exists comercial;

create table comercial.mensaje_contacto (
  id bigint generated by default as identity not null,
  nombre text not null,
  correo text not null,
  telefono text,
  mensaje text not null,
  origen text not null default 'sitio_web'::text,
  atendido boolean not null default false,
  fecha_creacion timestamp with time zone not null default now()
);

create table comercial.plan_pagina_web (
  id bigint generated by default as identity not null,
  clave text not null,
  nombre text not null,
  precio numeric(10,2) not null,
  moneda text not null default 'MXN'::text,
  tipo_pago text not null default 'unico'::text,
  secciones_maximas integer,
  propuestas_diseno integer,
  rondas_cambios integer,
  caracteristicas jsonb not null default '[]'::jsonb,
  destacado boolean not null default false,
  orden integer not null,
  activo boolean not null default true,
  fecha_creacion timestamp with time zone not null default now(),
  fecha_modificacion timestamp with time zone
);

alter table comercial.mensaje_contacto enable row level security;

alter table comercial.plan_pagina_web enable row level security;

alter table comercial.mensaje_contacto add constraint mensaje_contacto_pkey PRIMARY KEY (id);

alter table comercial.plan_pagina_web add constraint plan_pagina_web_clave_key UNIQUE (clave);

alter table comercial.plan_pagina_web add constraint plan_pagina_web_pkey PRIMARY KEY (id);

alter table comercial.plan_pagina_web add constraint plan_pagina_web_tipo_pago_check CHECK ((tipo_pago = ANY (ARRAY['unico'::text, 'mensual'::text])));

create policy lectura_publica on comercial.plan_pagina_web as permissive for SELECT to anon, authenticated
  using ((activo = true));

