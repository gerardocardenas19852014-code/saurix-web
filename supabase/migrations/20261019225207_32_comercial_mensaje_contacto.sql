create table comercial.mensaje_contacto (
  id bigint generated by default as identity primary key,
  nombre text not null,
  correo text not null,
  telefono text,
  mensaje text not null,
  origen text not null default 'sitio_web',
  atendido boolean not null default false,
  fecha_creacion timestamptz not null default now()
);

comment on table comercial.mensaje_contacto is
  'Mensajes enviados desde el formulario de contacto del sitio web publico de Saurix. Solo se escribe via seguridad.crear_mensaje_contacto (SECURITY DEFINER); sin politicas de RLS para anon/authenticated.';

alter table comercial.mensaje_contacto enable row level security;

create or replace function seguridad.crear_mensaje_contacto(
  p_nombre text,
  p_correo text,
  p_telefono text,
  p_mensaje text
)
returns bigint
language plpgsql
security definer
set search_path to ''
as $$
declare
  v_id bigint;
begin
  if coalesce(trim(p_nombre), '') = '' then
    raise exception 'El nombre es obligatorio.';
  end if;

  if coalesce(trim(p_correo), '') = '' or position('@' in p_correo) = 0 then
    raise exception 'Correo electronico invalido.';
  end if;

  if coalesce(trim(p_mensaje), '') = '' then
    raise exception 'El mensaje es obligatorio.';
  end if;

  if length(p_mensaje) > 4000 then
    raise exception 'El mensaje es demasiado largo.';
  end if;

  insert into comercial.mensaje_contacto (nombre, correo, telefono, mensaje)
  values (
    trim(p_nombre),
    trim(lower(p_correo)),
    nullif(trim(coalesce(p_telefono, '')), ''),
    trim(p_mensaje)
  )
  returning id into v_id;

  return v_id;
end;
$$;

grant usage on schema seguridad to anon, authenticated;
grant execute on function seguridad.crear_mensaje_contacto(text,text,text,text) to anon, authenticated;