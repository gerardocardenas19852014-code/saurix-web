
-- Esquema nuevo para datos comerciales propios de Saurix (no ligados a ninguna
-- empresa/tenant cliente, a diferencia de los demás esquemas del sistema).
create schema if not exists comercial;

create table comercial.plan_pagina_web (
  id bigint generated by default as identity primary key,
  clave text not null unique,
  nombre text not null,
  precio numeric(10,2) not null,
  moneda text not null default 'MXN',
  tipo_pago text not null default 'unico' check (tipo_pago in ('unico','mensual')),
  secciones_maximas integer,
  propuestas_diseno integer,
  rondas_cambios integer,
  caracteristicas jsonb not null default '[]'::jsonb,
  destacado boolean not null default false,
  orden integer not null,
  activo boolean not null default true,
  fecha_creacion timestamptz not null default now(),
  fecha_modificacion timestamptz
);

comment on table comercial.plan_pagina_web is
  'Planes de paginas web que Saurix vende a sus clientes (pago unico). No esta ligada a empresa_id porque es oferta comercial propia de Saurix, no dato de un cliente/tenant.';

alter table comercial.plan_pagina_web enable row level security;

-- Lectura publica (para alimentar la pagina web de mercadeo / cotizaciones);
-- solo el service_role puede escribir (sin politicas de insert/update/delete).
